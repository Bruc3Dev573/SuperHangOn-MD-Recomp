void ui_clear(void)
{
  memset(ui_canvas, 0, sizeof ui_canvas);
}

void ui_box(int x, int y, int w, int h, uint32_t argb)
{
  for (int yy = y < 0 ? 0 : y; yy < y + h && yy < UI_H; yy++)
    for (int xx = x < 0 ? 0 : x; xx < x + w && xx < UI_W; xx++)
      ui_canvas[yy][xx] = argb;
}

int ui_text_width(int scale, const char *text)
{
  return (int)strlen(text) * 6 * scale - scale;
}

void ui_text(int x, int y, int scale, uint32_t argb, const char *text)
{
  for (int i = 0; text[i]; i++) {
    unsigned char ch = (unsigned char)toupper((unsigned char)text[i]);
    const uint8_t *g = font5x7[ch < 128 ? ch : 0];
    for (int row = 0; row < 7; row++)
      for (int col = 0; col < 5; col++)
        if (g[row] & (0x10 >> col))
          ui_box(x + (i * 6 + col) * scale, y + row * scale, scale, scale, argb);
  }
}
